  const localeKey = 'lectureHall.locale';
  let saved;
  try { saved = localStorage.getItem(localeKey); } catch {}
  let language = saved === 'en' || saved === 'zh'
    ? saved
    : /^zh\b/i.test(navigator.language) ? 'zh' : 'en';

  function t(key, values = {}) {
    const template = language === 'zh' && Object.hasOwn(chinese, key) ? chinese[key] : key;
    return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
  }

  function message(text) {
    if (!text) return '';
    const match = /^Xiaohongshu could not load this video \((XHS_[A-Z0-9_]+)\)\.$/.exec(text);
    return match ? t('Xiaohongshu could not load this video ({code}).', {code: match[1]}) : t(text);
  }

  function render() {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    document.title = t('Private Lecture Hall');
    document.querySelector('meta[name="description"]').content =
      t('Choose a seat and watch a lecture in your own 3D lecture hall.');
    for (const element of document.querySelectorAll('[data-i18n]')) {
      element.textContent = t(element.dataset.i18n);
    }
    for (const attr of ['placeholder', 'aria-label', 'title']) {
      for (const element of document.querySelectorAll(`[data-i18n-${attr}]`)) {
        element.setAttribute(attr, t(element.getAttribute(`data-i18n-${attr}`)));
      }
    }
    for (const button of document.querySelectorAll('[data-language]')) {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    }
  }

  function getCountLabel(count) {
    if (language === 'zh') return count + ' 人';
    return count + (count === 1 ? ' person' : ' people');
  }

  window.hallI18n = {t, message, getCountLabel, get language() { return language; }};
  for (const button of document.querySelectorAll('[data-language]')) {
    button.addEventListener('click', () => {
      if (button.dataset.language === language) return;
      language = button.dataset.language;
      try { localStorage.setItem(localeKey, language); } catch {}
      render();
      document.dispatchEvent(new Event('hall-language-change'));
    });
  }
  render();
